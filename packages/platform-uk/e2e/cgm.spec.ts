import AxeBuilder from "@axe-core/playwright";
import { expect, test, type Page } from "@playwright/test";

import { applyApiCookiesToPage, createFreshTestUser, createOnboardedTestUser, signInViaApi } from "./helpers/auth";

/**
 * Week 8 "done when": a clinic uploads a patient's CGM export and sees consensus metrics and the AGP; a patient uploads
 * their own export (choosing the date order when ambiguous) and the clinician checks it before it counts.
 */
async function expectNoCriticalA11y(page: Page) {
  const results = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"]).analyze();
  expect(results.violations.filter((v) => v.impact === "critical").map((v) => v.id)).toEqual([]);
}

/** 14 days of 5-minute Dexcom-style rows (London wall clock, mg/dL) with a known mix: 70% in range, 10% below. */
function dexcomCsv() {
  const lines = ["Index,Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Event Subtype,Patient Info,Device Info,Source Device ID,Glucose Value (mg/dL),Insulin Value (u),Carb Value (grams),Duration (hh:mm:ss),Glucose Rate of Change (mg/dL/min),Transmitter Time (Long Integer),Transmitter ID"];
  const cycle = [50, 65, ...Array(14).fill(120), 200, 200, 200, 300];
  // A fixed summer fortnight: no clock change inside it, whatever day the test runs.
  const end = new Date(Date.UTC(2026, 5, 15));
  const fmt = new Intl.DateTimeFormat("en-GB", { timeZone: "Europe/London", year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit", hourCycle: "h23" });
  let i = 0;
  for (let t = end.getTime() - 14 * 86_400_000; t < end.getTime(); t += 300_000, i++) {
    const p = Object.fromEntries(fmt.formatToParts(new Date(t)).map((x) => [x.type, x.value]));
    lines.push(`${i + 1},${p.year}-${p.month}-${p.day}T${p.hour}:${p.minute}:${p.second},EGV,,,,G7,${cycle[i % cycle.length]},,,,,,`);
  }
  return lines.join("\n");
}

/** LibreView-style, 15-minute historic rows on 5 and 6 June 2026, written day-first (05-06, 06-06): ambiguous by design. */
function libreCsv() {
  const lines = ["Glucose Data,Generated on,,Generated by,Test", "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L"];
  for (const dd of ["05", "06"]) for (let h = 8; h < 10; h++) for (const mi of ["00", "15", "30", "45"]) lines.push(`FreeStyle Libre 2,ABC,${dd}-06-2026 ${String(h).padStart(2, "0")}:${mi},0,${(5 + (h % 3)).toFixed(1)},`);
  return lines.join("\n");
}

/** Generic CSV with offsets: 14 days of 5-minute readings (a patient's own full export). */
function genericCsv() {
  const lines = ["timestamp,glucose mmol/L"];
  const end = Date.UTC(2026, 6, 15);
  for (let t = end - 14 * 86_400_000, i = 0; t < end; t += 300_000, i++) lines.push(`${new Date(t).toISOString()},${(6 + (i % 4) * 0.5).toFixed(1)}`);
  return lines.join("\n");
}

test("cgm: clinic and patient uploads, consensus metrics, AGP, and checking the patient's upload", async ({ browser, baseURL }) => {
  test.setTimeout(240_000);
  const stamp = Date.now();
  const clinic = await browser.newContext();
  await createOnboardedTestUser(clinic.request, baseURL!, { role: "nurse", label: "cgm-nurse" });
  const org = await (await clinic.request.post("/api/orgs", { data: { name: `Glucose Clinic ${stamp}`, kind: "diabetes_centre" } })).json();
  await clinic.request.patch(`/api/orgs/${org.id}`, { data: { locale: { timezone: "Europe/London", glucoseUnit: "mmol/L" } } });
  const imported = await (await clinic.request.post(`/api/orgs/${org.id}/patients`, { data: { patients: [
    { recordRef: `GC-1-${stamp}`, givenName: "Ravi", familyName: `Sensor${stamp}`, dateOfBirth: "1988-08-08", diabetesType: "type_1" },
    { recordRef: `GC-2-${stamp}`, givenName: "Sofia", familyName: `Libre${stamp}`, dateOfBirth: "1992-02-02", diabetesType: "type_1" },
  ] } })).json();

  // 1. The nurse uploads Ravi's Dexcom export: preview first, then save; metrics and AGP appear.
  const page = await clinic.newPage();
  await applyApiCookiesToPage(page, clinic.request);
  await page.addInitScript(() => window.localStorage.setItem("aksh_cookie_consent", "essential"));
  await page.goto("/dashboard/network");
  await page.getByRole("tab", { name: "patients" }).click({ timeout: 20_000 });
  await page.locator("[data-registry] button", { hasText: `Sensor${stamp}` }).click({ timeout: 20_000 });
  const panel = page.locator("[data-patient-detail] [data-cgm-panel]");
  await expect(panel).toContainText("No CGM data yet");
  await panel.getByLabel("CGM export file").setInputFiles({ name: "clarity.csv", mimeType: "text/csv", buffer: Buffer.from(dexcomCsv()) });
  await expect(panel.locator("[data-cgm-preview]")).toContainText("Dexcom Clarity export in mg/dL · 4032 readings");
  await panel.getByRole("button", { name: /^Save 4032 readings/ }).click();
  await expect(panel.getByRole("status").first()).toContainText("4032 readings saved", { timeout: 20_000 });
  await expect(panel.locator("[data-cgm-metrics]")).toContainText("70%");
  await expect(panel.locator("[data-cgm-flags]")).toContainText("time below range is 4% or more");
  await expect(panel.getByRole("img", { name: /Ambulatory glucose profile/ })).toBeVisible();
  await expectNoCriticalA11y(page);

  // 2. Sofia links her app and uploads her LibreView export; the dates are ambiguous so she chooses day-first.
  const invite = await (await clinic.request.post(`/api/orgs/${org.id}/invites`, { data: { kind: "patient", patientId: imported.rows[1].id } })).json();
  const patient = await browser.newContext();
  const user = await createFreshTestUser(patient.request, baseURL!, { role: "patient", label: "cgm-patient" });
  await patient.request.post("/api/onboarding/complete", { data: { role: "patient", fullName: "Sofia Libre", identity: { firstName: "Sofia", inviteCode: invite.code, dateOfBirth: "1992-02-02" } } });
  await signInViaApi(patient.request, baseURL!, user.email, user.password);
  const ppage = await patient.newPage();
  await applyApiCookiesToPage(ppage, patient.request);
  await ppage.addInitScript(() => window.localStorage.setItem("aksh_cookie_consent", "essential"));
  await ppage.goto("/dashboard/patient");
  const mine = ppage.locator("[data-cgm-panel]");
  await expect(mine).toContainText("No CGM data yet", { timeout: 20_000 });
  await mine.getByLabel("CGM export file").setInputFiles({ name: "libreview.csv", mimeType: "text/csv", buffer: Buffer.from(libreCsv()) });
  await expect(mine.locator("[data-cgm-preview]")).toContainText("day/month or month/day");
  await mine.getByRole("button", { name: /Day first/ }).click();
  await expect(mine.locator("[data-cgm-preview]")).toContainText("LibreView export in mmol/L · 16 readings");
  await mine.getByRole("button", { name: /^Save 16 readings/ }).click();
  await expect(mine.getByRole("status").first()).toContainText("16 readings saved");
  await expectNoCriticalA11y(ppage);

  // 3. Sofia also uploads a full fortnight. Her data waits for a clinician before it counts.
  await mine.getByLabel("CGM export file").setInputFiles({ name: "mine.csv", mimeType: "text/csv", buffer: Buffer.from(genericCsv()) });
  await expect(mine.locator("[data-cgm-preview]")).toContainText("4032 readings");
  await mine.getByRole("button", { name: /^Save 4032 readings/ }).click();
  await expect(mine.getByRole("status").first()).toContainText("4032 readings saved");

  // 4. The clinician sees two patient uploads waiting, reviews them, and they count.
  await page.locator("[data-registry] button", { hasText: `Libre${stamp}` }).click();
  const sofia = page.locator("[data-patient-detail] [data-cgm-panel]");
  await expect(sofia.locator("[data-cgm-unchecked]")).toContainText("2 uploads by the patient");
  await sofia.getByRole("button", { name: /Mark patient's CGM data as reviewed/ }).click();
  await expect(sofia.getByRole("status").first()).toContainText("reviewed; it now counts");
  await expect(sofia.locator("[data-cgm-unchecked]")).toHaveCount(0);

  await patient.close();
  await clinic.close();
});
