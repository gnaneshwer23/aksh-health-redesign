import { z } from "zod";

/**
 * Personalised health plan artifact — draft only, HITL required, never auto-EHR.
 */

export const healthPlanSectionSchema = z.object({
  id: z.enum(["prevention", "treatment", "medications", "follow_up", "coaching"]),
  title: z.string(),
  items: z.array(z.string()).min(1),
  clinical: z.boolean()
});

export const healthPlanDraftSchema = z.object({
  id: z.string(),
  patientId: z.string(),
  patientLabel: z.string(),
  status: z.literal("DRAFT"),
  createdAt: z.string(),
  createdBy: z.string(),
  trigger: z.enum(["hitl_accept", "manual_request", "risk_state_review"]),
  sections: z.array(healthPlanSectionSchema).min(1),
  safetyNotes: z.array(z.string()),
  hitlRequired: z.literal(true),
  ehrWrite: z.literal(false),
  physiologicalTwin: z.literal(false)
});

export type HealthPlanDraft = z.infer<typeof healthPlanDraftSchema>;

export type HealthPlanInput = {
  patientId: string;
  patientLabel?: string;
  createdBy: string;
  trigger?: HealthPlanDraft["trigger"];
  conditions?: string[];
  medications?: string[];
  riskSignals?: string[];
  caseId?: string;
};

export function buildPersonalisedHealthPlanDraft(input: HealthPlanInput): HealthPlanDraft {
  const patientLabel = input.patientLabel?.trim() || input.patientId;
  const conditions = input.conditions?.length ? input.conditions : ["Review active conditions with clinician"];
  const medications = input.medications?.length
    ? input.medications
    : ["No medication changes proposed — clinician to confirm current list"];
  const riskSignals = input.riskSignals?.length
    ? input.riskSignals
    : ["No additional risk signals supplied"];

  const draft: HealthPlanDraft = {
    id: `plan-${input.patientId}-${Date.now()}`,
    patientId: input.patientId,
    patientLabel,
    status: "DRAFT",
    createdAt: new Date().toISOString(),
    createdBy: input.createdBy,
    trigger: input.trigger ?? "manual_request",
    sections: [
      {
        id: "prevention",
        title: "Prevention",
        clinical: true,
        items: [
          "Safety-netting advice drafted for clinician edit",
          `Address contributing signals: ${riskSignals.slice(0, 2).join("; ")}`,
          "Lifestyle coaching may be offered separately (not clinical advice)"
        ]
      },
      {
        id: "treatment",
        title: "Treatment",
        clinical: true,
        items: [
          `Focus conditions: ${conditions.slice(0, 3).join("; ")}`,
          "No autonomous treatment change — HITL Accept required before staging"
        ]
      },
      {
        id: "medications",
        title: "Medications",
        clinical: true,
        items: medications.slice(0, 5)
      },
      {
        id: "follow_up",
        title: "Follow-up",
        clinical: true,
        items: [
          "Schedule clinician-confirmed follow-up window",
          input.caseId ? `Linked case: ${input.caseId}` : "Link to accepted review case when available"
        ]
      },
      {
        id: "coaching",
        title: "Wellness coaching (optional)",
        clinical: false,
        items: [
          "Nutrition / sleep coaching drafts available under coaching_wellness consent",
          "Explicitly not clinical advice; escalate to clinician if red flags"
        ]
      }
    ],
    safetyNotes: [
      "Personalised health plan is a DRAFT artifact only.",
      "HITL Accept/Edit/Reject required before any staging or record impact.",
      "Zero autonomous EHR write.",
      "Not generated by a physiological digital twin simulation."
    ],
    hitlRequired: true,
    ehrWrite: false,
    physiologicalTwin: false
  };

  return healthPlanDraftSchema.parse(draft);
}
